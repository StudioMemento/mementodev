import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { verifyCarouselScheduler } from '../tests/v22/carousel-scheduler.mjs';
import { verifyChromeSignal } from '../tests/v22/chrome-signal.mjs';
import { verifyMenuHtml } from '../tests/v22/freeze-contract.mjs';
const json = async p => JSON.parse(await readFile(p,'utf8'));
const digest = b => createHash('sha256').update(b).digest('hex');
const baseline = await json('tests/v23/baseline.json');
for (const [file, hash] of Object.entries(baseline)) assert.equal(digest(await readFile(file)),hash,`Frozen V22 asset/content changed: ${file}`);
const menuBytes = await readFile('src/data/menu.json');
assert.notEqual(digest(Buffer.concat([menuBytes,Buffer.from('changed')])),baseline['src/data/menu.json'],'Integrity negative control failed');
const html = await readFile('dist/index.html','utf8');
const oldFixture = await json('tests/v22/frozen-v21.json');
verifyMenuHtml(html,oldFixture.menuHtmlSha256);
assert.throws(()=>verifyMenuHtml(html.replaceAll('Margherita Classica','Changed menu item'),oldFixture.menuHtmlSha256));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'Duplicate IDs');
const idSet=new Set(ids);
for(const id of ['home','pizza-slider','cornicione','menu','gallery','customer','social','dove']) assert.ok(idSet.has(id),`Missing section: ${id}`);
assert.ok(!idSet.has('catshow'),'Redundant category carousel remains');
for(const m of html.matchAll(/href="#([^"]+)"/g)) assert.ok(idSet.has(m[1]),`Broken internal link: ${m[1]}`);
assert.match(html,/v23-ready/);assert.match(html,/content="[^"\n]*V23/);assert.match(html,/noindex,nofollow/);
const hero=html.slice(html.indexOf('id="home"'),html.indexOf('id="pizza-slider"'));
assert.match(hero,/La pizza di sempre,/);assert.match(hero,/con un tocco in più!/);assert.ok(!hero.includes('Scopri il menù'));
const oven=html.slice(html.indexOf('id="pizza-slider"'),html.indexOf('id="cornicione"'));
assert.equal((oven.match(/class="pizza-dot"/g)||[]).length,10);
assert.equal((oven.match(/class="pizza-arrow"/g)||[]).length,2);
assert.ok(!/carousel-counter|carousel-play|carousel-pause|Trascina, scegli/.test(oven));
const crust=html.slice(html.indexOf('id="cornicione"'),html.indexOf('id="menu"'));
assert.match(crust,/Il cornicione con qualcosa in più!/);assert.match(crust,/Scegli il ripieno e rendi la tua pizza unica\./);
assert.equal((crust.match(/crust-option crust-card/g)||[]).length,3);assert.ok(!/<a\b/.test(crust));
for(const name of ['ricotta','brie','gorgonzola']) for(const size of [480,960]) {
 const p=`public/assets/cornicione/${name}-${size}.webp`, b=await readFile(p);
 assert.equal(b.toString('ascii',0,4),'RIFF');assert.equal(b.toString('ascii',8,12),'WEBP');assert.ok(b.length<200000,`Photo weight budget: ${p}`);await stat(p.replace('public/','dist/'));
}
const nav=html.match(/<nav class="vr-dock vr-dock-v23"[\s\S]*?<\/nav>/)?.[0];
assert.ok(nav,'Dock missing');assert.equal((nav.match(/class="dock-tile"/g)||[]).length,4);assert.ok(!/dock-label/.test(nav));assert.equal((nav.match(/<a [^>]*aria-label=/g)||[]).length,4);
for(const m of html.matchAll(/(?:src|href)="(\/[^"#?]+)"/g)) if(!m[1].startsWith('//')) await stat(`dist${m[1]}`);
await verifyCarouselScheduler({count:10, interval:6500, speed:0});
await verifyChromeSignal();
console.log(`V23 CONTRACT OK — ${Object.keys(baseline).length} frozen files, exact menu HTML, 6 WebP assets, navigation, real carousel scheduler and negative controls.`);
